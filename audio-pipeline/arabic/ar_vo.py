SR = None; out = None; meta = []
def synth(t, speed):
    a = tts.generate(t, sid=0, speed=speed); s = np.array(a.samples, dtype=np.float32)
    thr = 0.02 * np.abs(s).max(); idx = np.where(np.abs(s) > thr)[0]
    return s[max(0, idx[0] - 200):idx[-1] + 1500], a.sample_rate
for i, (st, en, t) in enumerate(L):
    base = 0.92  # slightly slower than default: calmer storytelling pace
    s, SR = synth(t, base)
    win = en - st
    sp = base
    for _ in range(4):
        if len(s) / SR <= win or sp >= 1.1: break
        sp = min(1.1, sp * (len(s) / SR) / win * 1.03)
        s, SR = synth(t, sp)
    if out is None: out = np.zeros(int(TOTAL * SR) + SR, dtype=np.float32)
    k = int(st * SR); out[k:k + len(s)] += s
    d = len(s) / SR
    meta.append(dict(i=i, start=st, end=round(st + d, 2), window=en, speed=round(sp, 3), over=round(st + d - en, 2)))
    print(f"{i:2d} {st:6.1f}-{st+d:6.1f} (win {en}) speed {sp:.2f} {'OVER '+str(round(st+d-en,2)) if st+d>en else ''}")
sf.write("build/vo_raw.wav", out[:int(TOTAL * SR)], SR)
json.dump(dict(voice=VOICE, lines=meta, text=[x[2] for x in L]), open("build/vo.json", "w"), ensure_ascii=False, indent=1)
